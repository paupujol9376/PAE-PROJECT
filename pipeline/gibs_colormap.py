"""Generate app/src/weather/imergColormap.ts from NASA GIBS' official GPM precipitation colormap.

    python -I pipeline/gibs_colormap.py [path/to/GPM_Precipitation_Rate.xml]

Source: https://gibs.earthdata.nasa.gov/colormaps/v1.3/GPM_Precipitation_Rate.xml (linked from the
IMERG_Precipitation_Rate_30min layer metadata). Only the "Rain Rate" colour map is kept.
The table lets the app turn a tile pixel back into mm/h (getValueAt) and draw the legend.
"""
import json, pathlib, re, sys, urllib.request

URL = "https://gibs.earthdata.nasa.gov/colormaps/v1.3/GPM_Precipitation_Rate.xml"
xml = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8") if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()
# the file has three maps: "Classifications" (no data), "Rain Rate", "Snow Rate"; keep rain
first = re.search(r'<ColorMap\s[^>]*title="Rain Rate"[^>]*>(.*?)</ColorMap>', xml, re.S).group(1)
rows = []
for e in re.findall(r"<ColorMapEntry([^>]*)/?>", first):
    g = lambda k: (re.search(k + r'="([^"]+)"', e) or [None, None])[1]
    if g("transparent") == "true" or not g("value"):
        continue
    lo = float(re.match(r"\[([-\d.]+)", g("value")).group(1))
    r, gg, b = (int(v) for v in g("rgb").split(","))
    rows.append([r, gg, b, lo])
out = pathlib.Path(__file__).resolve().parents[1] / "app/src/weather/imergColormap.ts"
out.write_text(
    "// GENERATED by pipeline/gibs_colormap.py from NASA GIBS GPM_Precipitation_Rate colormap (rain). Do not edit.\n"
    f"// [r, g, b, lower bound in mm/h] — {len(rows)} entries.\n"
    f"export const IMERG_COLORS: [number, number, number, number][] = {json.dumps(rows)};\n",
    encoding="utf-8",
)
print(f"{len(rows)} entries -> {out}")
