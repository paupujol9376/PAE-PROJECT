"""Generate tokens.css from tokens.json and check WCAG contrast for every theme.

    python -I replica/03-design/build_tokens.py [--contrast path/to/contrast.py]

Writes replica/03-design/tokens.css and replica/03-design/contrast-report.txt.
Exit code 1 if any pair fails WCAG AA. Standard library only.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
NEEDS = {"normal": 4.5, "large": 3.0, "ui": 3.0}


def lum(hex_):
    h = hex_.lstrip("#")
    def ch(c):
        c = int(c, 16) / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = ch(h[0:2]), ch(h[2:4]), ch(h[4:6])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def check(palette, pairs, label, lines):
    fails = 0
    for p in pairs:
        fg, bg, kind = p[0], p[1], (p[2] if len(p) > 2 else "normal")
        r = ratio(palette[fg], palette[bg])
        ok = r >= NEEDS[kind]
        fails += not ok
        lines.append(f"{'PASS' if ok else 'FAIL'}  {label:<10} {fg:<22} on {bg:<16} {kind:<6} {r:5.2f}:1 (needs {NEEDS[kind]})")
    return fails


def css_block(selector, palette):
    body = "\n".join(f"  --{k}: {v};" for k, v in palette.items())
    return f"{selector} {{\n{body}\n}}\n"


def main():
    t = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
    lines, fails = [], 0
    for theme, pal in t["color"].items():
        fails += check(pal, t["pairs"], theme, lines)
    for theme in ("dark", "light", "a11y"):
        fails += check(t["map"][theme], t["map"]["pairs"], "map-" + theme, lines)
    lines.append(f"\n{'ALL PASS' if not fails else str(fails) + ' FAIL(S)'}")
    (HERE / "contrast-report.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))

    out = ["/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */\n"]
    statics = {}
    for k, v in t["type"].items():
        statics[f"font-{k}-size"] = f"{v['size']}px"
        statics[f"font-{k}-line"] = f"{v['line']}px"
        statics[f"font-{k}-weight"] = str(v["weight"])
    for i, v in enumerate(t["space"]):
        statics[f"space-{i}"] = f"{v}px"
    for k, v in t["radius"].items():
        statics[f"radius-{k}"] = f"{v}px"
    for k, v in t["shadow"].items():
        statics[f"shadow-{k}"] = v
    for k, v in t["motion"].items():
        statics[f"motion-{k}"] = v
    for k, v in t["layout"].items():
        statics[k] = f"{v}px" if isinstance(v, (int, float)) else v
    statics["font-sans"] = t["font"]["sans"]
    statics["font-mono"] = t["font"]["mono"]
    out.append(css_block(":root", statics))
    dark = {**t["color"]["dark"], **t["map"]["dark"]}
    light = {**t["color"]["light"], **t["map"]["light"]}
    a11y = {**t["color"]["a11y"], **t["map"]["a11y"]}
    out.append(css_block(":root, :root[data-theme=\"dark\"]", dark))
    out.append("@media (prefers-color-scheme: light) {\n" + css_block(":root:not([data-theme])", light).replace("\n", "\n  ").rstrip() + "\n}\n")
    out.append(css_block(":root[data-theme=\"light\"]", light))
    out.append(css_block(":root[data-theme=\"a11y\"]", a11y))
    out.append(":root { color-scheme: dark; }\n:root[data-theme=\"light\"] { color-scheme: light; }\n")
    out.append("[lang=\"si\"], [lang=\"ta\"] {\n  --font-xs-line: 20px; --font-sm-line: 24px; --font-base-line: 28px;\n  --font-lg-line: 32px; --font-xl-line: 36px; --font-metric-line: 40px;\n}\n")
    (HERE / "tokens.css").write_text("\n".join(out), encoding="utf-8")
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
